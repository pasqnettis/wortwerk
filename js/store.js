import { NON_TEXT_MODEL } from "./llm/providers.js";

// All learner progress lives in localStorage under one key.
// Everything stays in this browser; "Export" in Settings makes a backup file.

const KEY = "wortwerk:v1";

const DEFAULTS = () => ({
  onboarded: false,
  level: "A1",
  known: {},            // lemma -> 1
  cards: {},            // lemma -> { word, en, ex, exEn, fsrs, added }
  read: {},             // textId -> ISO date finished
  myTexts: [],          // texts generated by the AI (source: "ai")
  seenSentences: {},    // tatoeba id -> 1 (dictation/speaking history)
  writings: [],         // free-writing submissions with AI feedback
  grammar: {},          // chapterId -> { read, best, total, at }
  news: {},             // "YYYY-MM-DD" -> { at, texts } daily news written by the AI
  userDict: { lemmas: {}, forms: {} }, // words missing from the offline dictionary, saved from AI explanations
  readPos: {},          // textId -> sentence index where read-aloud was paused
  stats: {},            // "YYYY-MM-DD" -> { reviews, dictation, speak, read, chat }
  settings: {
    provider: "anthropic", // see js/llm/providers.js
    keys: {},              // providerId -> API key (never exported)
    models: {},            // providerId -> model id (default: provider.defaultModel)
    baseUrls: {},          // providerId -> base URL override (custom server, Ollama elsewhere)
    voice: "",
    rate: 0.9,
    highlight: true,
    autoSpeakChat: true,
  },
});

function load() {
  try {
    const raw = localStorage.getItem(KEY);
    if (!raw) return DEFAULTS();
    const data = JSON.parse(raw);
    const d = DEFAULTS();
    return migrate({ ...d, ...data, settings: { ...d.settings, ...(data.settings || {}) } });
  } catch {
    return DEFAULTS();
  }
}

/** Upgrade data saved by older versions of the app. */
function migrate(state) {
  const st = state.settings;
  // v1 stored a single Claude key/model
  if (st.apiKey) { st.keys = { ...st.keys, anthropic: st.keys?.anthropic || st.apiKey }; }
  if (st.model) { st.models = { ...st.models, anthropic: st.models?.anthropic || st.model }; }
  delete st.apiKey;
  delete st.model;
  for (const t of state.myTexts || []) if (t.source === "claude") t.source = "ai";
  state.userDict = { lemmas: {}, forms: {}, ...(state.userDict || {}) };
  // gemini-2.5-flash (the first Gemini default) is no longer offered to new Gemini accounts
  if (st.models?.gemini === "gemini-2.5-flash") delete st.models.gemini;
  // an image/speech model picked by mistake from "Load models" -> back to the provider default
  for (const [prov, model] of Object.entries(st.models || {})) if (NON_TEXT_MODEL.test(model)) delete st.models[prov];
  return state;
}

export const S = load();

let timer = null;
export function save() {
  clearTimeout(timer);
  timer = setTimeout(() => {
    try {
      localStorage.setItem(KEY, JSON.stringify(S));
    } catch (e) {
      console.warn("Could not save progress", e);
    }
  }, 150);
}

const listeners = new Set();
export function onChange(fn) { listeners.add(fn); return () => listeners.delete(fn); }
export function changed() { save(); listeners.forEach((fn) => fn()); }

export function today() {
  const d = new Date();
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
}

export function track(kind, n = 1) {
  const day = (S.stats[today()] ||= {});
  day[kind] = (day[kind] || 0) + n;
  changed();
}

export function dayTotal(key) {
  const d = S.stats[key];
  return d ? Object.values(d).reduce((a, b) => a + b, 0) : 0;
}

export function streak() {
  let n = 0;
  const d = new Date();
  if (!dayTotal(fmt(d))) d.setDate(d.getDate() - 1); // today not started yet: count from yesterday
  while (dayTotal(fmt(d))) { n++; d.setDate(d.getDate() - 1); }
  return n;
}

export function fmt(d) {
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
}

export function exportData() {
  return JSON.stringify({ ...S, settings: { ...S.settings, keys: {} } }, null, 1);
}

export function importData(json) {
  const data = JSON.parse(json);
  const keys = S.settings.keys;
  Object.keys(S).forEach((k) => delete S[k]);
  Object.assign(S, migrate({ ...DEFAULTS(), ...data, settings: { ...DEFAULTS().settings, ...(data.settings || {}) } }));
  S.settings.keys = keys; // keep this browser's keys
  changed();
}

export function resetAll() {
  localStorage.removeItem(KEY);
  location.reload();
}
